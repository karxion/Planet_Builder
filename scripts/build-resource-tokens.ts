import { createRequire } from "node:module";
import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";

const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || "sharp");
const originals = resolve("docs/04-report/assets/resource-tokens/originals");
const output = resolve("public/assets/rpg-map/resource-tokens");
const previews = resolve("docs/04-report/assets/resource-tokens");
const tokens = [
  ["wood", "Timber", "목재"], ["stone", "Stone", "석재"], ["ore", "Metal Ore", "금속 광석"],
  ["gold", "Precious Metals", "귀금속"], ["grain", "Grain", "곡물"], ["fish", "Fish", "어류"],
  ["livestock", "Livestock", "가축"], ["gems", "Gemstones", "보석"], ["herbs", "Plants and Spices", "약초·향신료"],
  ["silk", "Textiles", "직물"], ["salt", "Salt", "소금"], ["crate", "Crafted Goods", "제작품"],
  ["horses", "Mounts", "탈것"], ["honey", "Honey and Wine", "꿀·포도주"], ["coal", "Coal", "석탄"],
  ["oil", "Oil and Tar", "석유·타르"]
] as const;

await mkdir(output, { recursive: true });
const images: Record<string, string> = {};
const checks: Array<{ id: string; width: number; height: number; transparentPixels: number; bytes: number }> = [];
let tiles = "";
for (const [index, [id, en, ko]] of tokens.entries()) {
  const input = await readFile(resolve(originals, `${id}.png`));
  const metadata = await sharp(input).metadata();
  if (!metadata.hasAlpha) throw new Error(`${id}: the original must have genuine transparency`);
  const { data, info } = await sharp(input).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  let transparentPixels = 0;
  for (let i = 3; i < data.length; i += info.channels) if (data[i] === 0) transparentPixels++;
  if (transparentPixels < info.width * info.height * 0.05) throw new Error(`${id}: insufficient transparent exterior`);
  const webp = await sharp(input).resize(256, 256, { fit: "contain", background: "#00000000" })
    .webp({ quality: 90, alphaQuality: 100, effort: 4 }).toBuffer();
  images[id] = `data:image/webp;base64,${webp.toString("base64")}`;
  await writeFile(resolve(output, `${id}.webp`), webp);
  checks.push({ id, width: metadata.width, height: metadata.height, transparentPixels, bytes: webp.length });
  const x = 28 + (index % 4) * 252;
  const y = 80 + Math.floor(index / 4) * 270;
  const preview = await sharp(input).resize(216, 216).png().toBuffer();
  tiles += `<g transform="translate(${x} ${y})"><image href="data:image/png;base64,${preview.toString("base64")}" x="16" width="216" height="216"/><text x="124" y="239" text-anchor="middle" fill="#eee8d8" font-size="17">${ko}</text><text x="124" y="260" text-anchor="middle" fill="#b9c5c3" font-size="13">${en}</text></g>`;
}
await writeFile(resolve("src/data/rpg-resource-token-images.ts"),
  `// Generated by scripts/build-resource-tokens.ts. Do not edit base64 artwork by hand.\nexport const RESOURCE_TOKEN_IMAGES: Readonly<Record<string, string>> = ${JSON.stringify(images, null, 2)};\n`);
execFileSync(process.execPath, [resolve("node_modules/@biomejs/biome/bin/biome"), "format", "--write", "src/data/rpg-resource-token-images.ts"], { stdio: "inherit" });
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="1064" height="1188" font-family="Malgun Gothic, Arial, sans-serif"><rect width="1064" height="1188" fill="#172629"/><text x="28" y="43" fill="#e7c785" font-size="25" font-weight="bold">판타지 행성 빌더 · RESOURCE TOKENS</text><text x="28" y="65" fill="#b9c5c3" font-size="13">16 individually generated RPG tokens · transparent artwork</text>${tiles}</svg>`;
await writeFile(resolve(previews, "contact-sheet.svg"), sheet);
await sharp(Buffer.from(sheet)).png().toFile(resolve(previews, "contact-sheet.png"));
await writeFile(resolve(previews, "validation.json"), JSON.stringify(checks, null, 2));
console.log(JSON.stringify({ tokens: checks.length, totalBytes: checks.reduce((n, c) => n + c.bytes, 0), checks }, null, 2));
