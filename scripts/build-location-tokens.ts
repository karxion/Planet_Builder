import { execFileSync } from "node:child_process";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import { resolve } from "node:path";

const require = createRequire(import.meta.url);
const sharp = require(process.env.SHARP_MODULE || "sharp");
const folder = resolve("docs/04-report/assets/location-tokens");
const output = resolve("public/assets/rpg-map/location-tokens");
const manifest: {id: string; prompt: string; path: string}[] = JSON.parse(await readFile(resolve(folder, "prompts.json"), "utf8"));
const images: Record<string, string> = {};
const checks: {id: string; width: number; height: number; transparentPixels: number; bytes: number}[] = [];
await mkdir(output, {recursive: true});
let tiles = "";
for (const [index, {id}] of manifest.entries()) {
  const input = await readFile(resolve(folder, "originals", `${id}.png`));
  const metadata = await sharp(input).metadata();
  if (!metadata.hasAlpha) throw new Error(`${id}: expected transparent original`);
  const {data, info} = await sharp(input).ensureAlpha().raw().toBuffer({resolveWithObject: true});
  let transparentPixels = 0;
  for (let i = 3; i < data.length; i += info.channels) if (data[i] === 0) transparentPixels++;
  if (transparentPixels < info.width * info.height * 0.05) throw new Error(`${id}: insufficient transparent margin`);
  const webp = await sharp(input).trim({background: "#00000000", threshold: 1})
    .resize(240, 240, {fit: "contain", background: "#00000000"})
    .extend({top: 8, bottom: 8, left: 8, right: 8, background: "#00000000"})
    .webp({quality: 90, alphaQuality: 100, effort: 4}).toBuffer();
  images[id] = `data:image/webp;base64,${webp.toString("base64")}`;
  await writeFile(resolve(output, `${id}.webp`), webp);
  checks.push({id, width: metadata.width, height: metadata.height, transparentPixels, bytes: webp.length});
  const x = 20 + index % 6 * 176, y = 76 + Math.floor(index / 6) * 204;
  const preview = `data:image/png;base64,${(await sharp(webp).png().toBuffer()).toString("base64")}`;
  tiles += `<g transform="translate(${x} ${y})"><image href="${preview}" width="160" height="160"/><text x="80" y="182" text-anchor="middle" fill="#eee8d8" font-size="14">${id}</text><image href="${preview}" x="112" y="164" width="32" height="32"/></g>`;
}
await writeFile(resolve("src/data/rpg-location-token-images.ts"),
  `// Generated by scripts/build-location-tokens.ts. Do not edit base64 artwork by hand.\nexport const LOCATION_TOKEN_IMAGES: Readonly<Record<string, string>> = ${JSON.stringify(images, null, 2)};\n`);
execFileSync(process.execPath, [resolve("node_modules/@biomejs/biome/bin/biome"), "format", "--files-max-size=2097152", "--write", "src/data/rpg-location-token-images.ts"], {stdio: "inherit"});
const height = 90 + Math.ceil(manifest.length / 6) * 204;
const sheet = `<svg xmlns="http://www.w3.org/2000/svg" width="1096" height="${height}" font-family="Arial, sans-serif"><rect width="1096" height="${height}" fill="#18282a"/><text x="24" y="40" fill="#e7c785" font-size="24">Fantasy Planet Builder - Location Tokens</text><text x="24" y="62" fill="#b9c5c3" font-size="13">${manifest.length} individually generated tokens / transparent artwork / 32px inset previews</text>${tiles}</svg>`;
await writeFile(resolve(folder, "contact-sheet.svg"), sheet);
await sharp(Buffer.from(sheet)).png().toFile(resolve(folder, "contact-sheet.png"));
await writeFile(resolve(folder, "validation.json"), JSON.stringify(checks, null, 2));
console.log(JSON.stringify({tokens: checks.length, totalBytes: checks.reduce((sum, token) => sum + token.bytes, 0)}, null, 2));
